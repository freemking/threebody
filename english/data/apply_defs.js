// Apply definitions
let totalApplied = 0;
for (let g = 4; g <= 9; g++) {
  const file = 'grade' + g + '.json';
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  let applied = 0;
  
  data.forEach(w => {
    if (w.explain.includes('is a common English word') || 
        w.explain.includes('is a common English phrase') ||
        w.explain.includes('is an adjective describing') ||
        w.explain.includes('is a noun referring') ||
        w.explain.includes('is an adverb describing') ||
        w.explain.includes('is the past tense') ||
        w.explain.includes('is the present participle') ||
        w.explain.includes('is an English expression')) {
      const wordLower = w.word.toLowerCase();
      if (defs[wordLower]) {
        const article = /^[aeiou]/i.test(wordLower) ? 'An' : 'A';
        w.explain = article + ' ' + w.word.toLowerCase() + ' is ' + defs[wordLower] + '.';
        applied++;
      }
    }
  });
  
  fs.writeFileSync(file, JSON.stringify(data, null, 2), 'utf8');
  console.log(file + ': ' + applied + ' explanations improved');
  totalApplied += applied;
}

